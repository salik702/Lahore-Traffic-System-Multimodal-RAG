PIPELINE_VERSION='2.1.1'
DISCLAIMER=('This report is generated by an AI-based traffic analysis system. Findings are preliminary and may contain errors. '
            'They are not official traffic challans or legally binding determinations. Final violations and penalties must be '
            'verified by the relevant authorities.')


def visual_analysis(path):
    import cv2
    started=time.perf_counter()
    image=cv2.imread(str(path))
    if image is None:raise RuntimeError('Decoded image could not be read')
    quality=assess_quality(image)
    timings={}
    warnings=[]
    with INFERENCE_LOCK:
        step=time.perf_counter()
        detections,engine=detect_objects(image)
        timings['vehicle_detection_ms']=round((time.perf_counter()-step)*1000,1)
        vehicles=[b for b in detections if b['class'] in VEHICLES]
        persons=[b for b in detections if b['class']=='person']
        poses=[]
        if quality['sufficient'] and any(v['class']=='motorcycle' and v.get('classification_status')=='supported' for v in vehicles) and persons:
            try:
                step=time.perf_counter()
                pose_boxes,pose_result=predict('pose',image,.4,640)
                if pose_result.keypoints is not None:
                    poses=[{'bbox':b['bbox'],'points':points} for b,points in zip(pose_boxes,pose_result.keypoints.data.tolist())]
                timings['pose_ms']=round((time.perf_counter()-step)*1000,1)
            except Exception:
                warnings.append('Pose inference unavailable; riding relationships cannot be confirmed.')
        candidates=associate_riders(detections,poses)
        if quality['sufficient'] and any(r['association']=='uncertain' for r in candidates):
            step=time.perf_counter()
            try:
                candidates=refine_riders(image,detections,poses)
            except Exception:
                warnings.append('Person-crop pose refinement unavailable; ambiguous rider relationships remain uncertain.')
            timings['pose_refinement_ms']=round((time.perf_counter()-step)*1000,1)
        step=time.perf_counter()
        try:
            if quality['sufficient']:riders,specialized=detect_helmets(image,candidates,persons)
            else:riders,specialized=match_heads(image,candidates,[],persons)
        except Exception:
            warnings.append('Helmet model unavailable; helmet findings withheld.')
            riders,specialized=match_heads(image,candidates,[],persons)
        heads=[b for b in specialized if b['class'] in POSITIVE | NEGATIVE]
        timings['helmet_ms']=round((time.perf_counter()-step)*1000,1)
        if len({r['vehicle_id'] for r in candidates})>policy()['max_motorcycle_crops']:
            warnings.append('Motorcycle crop budget reached; some heads are not assessable.')
        step=time.perf_counter()
        try:
            plate_results,plate_boxes=detect_plates(image,vehicles,specialized)
        except Exception:
            warnings.append('Plate localization unavailable; no plate-related violation inferred.')
            plate_boxes=[]
            plate_results=[{'vehicle_id':v['id'],'status':'unavailable','text':None,'ocr_confidence':None,
                            'confidence':None,'plate_ids':[],'mounting_area_verified':False,
                            'reason':'Number plate not readable. Plate localization is unavailable.'}
                           for v in vehicles if v['class']!='bicycle']
        timings['plate_detection_and_ocr_ms']=round((time.perf_counter()-step)*1000,1)
        if not quality['sufficient']:warnings.extend(quality['reasons'])
        if not vehicles:
            warnings.append('No supported vehicle detected. Interior views, occlusion or small vehicles may prevent vehicle recognition; no compliance conclusion follows.')
        evidence=[]
        for head in heads:
            crop=crop_region(image,head['bbox'])
            if crop.size:evidence.append({'id':head['id'],'vehicle_id':head['vehicle_id'],
                'label':head['class'],'bbox':head['bbox'],'confidence':head['confidence'],'image_url':image_url(crop,520)})
        observations=[{'type':'motorcycle_occupancy','vehicle_id':v,'supported_rider_count':n}
                      for v,n in Counter(r['vehicle_id'] for r in riders if r['association']=='supported').items()]
        annotated=annotate(image,detections,heads,plate_boxes)
    timings['visual_total_ms']=round((time.perf_counter()-started)*1000,1)
    return {'success':True,'detections':detections,'vehicles':vehicles,'persons':persons,'riders':riders,
        'occupants':associate_occupants(detections),'helmet_detections':heads,
        'helmet_results':[{'rider_id':r['id'],'vehicle_id':r['vehicle_id'],'status':r['helmet_status'],
                           'confidence':r['helmet_confidence'],'reason':r['helmet_reason']} for r in riders],
        'plate_results':plate_results,'plate_detections':plate_boxes,'observations':observations,
        'traffic_signs':[{**b,'interpretation':'Generic stop sign; no violation inferred'} for b in detections if b['class']=='stop sign'],
        'evidence_crops':evidence,'annotated_image_url':annotated,'original_image_url':image_url(image),
        'engine':engine,'helmet_engine':'Motorcycle-context YOLOv8n (AutonomousUI)',
        'plate_engine':'YOLOv9 tiny ONNX + RapidOCR PP-OCRv4 CPU',
        'pipeline_version':PIPELINE_VERSION,'model_version':PIPELINE_VERSION,'image_quality':quality,'timings':timings,
        'image_size':{'width':image.shape[1],'height':image.shape[0]},'warnings':warnings,
        'capabilities':capabilities(),'confidence_calibration':'Uncalibrated model scores; conservative configured thresholds, not probabilities of guilt.',
        'thresholds':policy(),'limitations':[
            'Single images do not establish movement; findings require manual review.',
            'Pakistan-specific precision/recall and OCR accuracy require a representative labeled held-out dataset.',
            'COCO has no separate van or rickshaw class; these cannot be reliably distinguished with these weights.',
            'Seated pose is conservative: occluded, merged or truncated people may be missed.',
            'Two matching OCR views can still share an error; plate text is unverified and must be checked against the crop.',
            'Missing, obscured and nonstandard plates are unsupported; unreadable or absent localization is insufficient.',
            'Seatbelt, phone use, loading, road behavior and license/registration modules are explicitly unsupported.',
            'Published Punjab fine amounts have no stated effective date. Other jurisdictions require separate verified records.',
        ],'disclaimer':DISCLAIMER,'models':model_metadata()}


def model_metadata():
    import os
    manifest=MODEL_DIR/'manifest.json'
    records=json.loads(manifest.read_text(encoding='utf-8')).get('models',[]) if manifest.is_file() else []
    for entry in records:
        kind={'vehicle_detector.pt':'vehicle','helmet_detector.pt':'helmet','rider_pose.pt':'pose','plate_detector.onnx':'plate'}.get(entry['filename'])
        if kind and os.getenv(f'{kind.upper()}_MODEL_PATH'):
            entry.update(name=f'Configured {kind} model; classes validated at initialization',version='User configured',sha256=None,license='User must verify configured model license')
    ocr_manifest=MODEL_DIR/'ocr_manifest.json'
    if ocr_manifest.is_file():
        ocr=json.loads(ocr_manifest.read_text(encoding='utf-8'))
        records.append({'name':ocr['name'],'filename':'Bundled OCR ONNX weights',
                        'version':ocr['package_version'],'license':ocr['license'],'source':ocr['source'],
                        'limitations':ocr['limitations']})
    return records


def finish_analysis(scene,settings,jurisdiction):
    import cv2
    started=time.perf_counter()
    fines=FineDatabase(settings.data_dir)
    if not fines.valid:scene['warnings'].append('Legal database unavailable: '+str(fines.error)+'. No penalty amount is asserted.')
    scene.update(analyze_evidence(scene,fines,jurisdiction))
    image=cv2.imdecode(np.frombuffer(base64.b64decode(scene['original_image_url'].split(',',1)[1]),dtype=np.uint8),1)
    primary=foreground_vehicle(scene['vehicles'],scene.get('image_size',{'width':image.shape[1],'height':image.shape[0]}))
    scene['primary_vehicle_id']=primary['id'] if primary else None
    scene['foreground_selection']={
        'method':'Apparent vehicle size and lower-frame position',
        'reason':'Estimated foreground subject, not a calibrated distance measurement. Select a different vehicle if needed.'}
    scene['report_scope']='One selected vehicle; surrounding vehicles are excluded.'
    by_id={v['id']:v for v in scene['vehicles']}
    for vehicle in scene['vehicle_results']:
        bounds=subject_bounds(by_id[vehicle['vehicle_id']],scene['riders'],image.shape)
        vehicle['focus_bbox']=bounds
        crop=crop_region(image,bounds)
        if crop.size:vehicle['image_url']=image_url(crop,1200)
        person_ids={r['person_id'] for r in vehicle['riders'] if r['association']=='supported'}
        detections=[d for d in scene['detections'] if d['id']==vehicle['vehicle_id'] or d['id'] in person_ids]
        heads=[d for d in scene['helmet_detections'] if d['vehicle_id']==vehicle['vehicle_id'] and d.get('association')=='supported']
        plates=[d for d in scene['plate_detections'] if d.get('vehicle_id')==vehicle['vehicle_id']]
        def local(boxes):
            return [{**b,'bbox':[b['bbox'][0]-bounds[0],b['bbox'][1]-bounds[1],
                                 b['bbox'][2]-bounds[0],b['bbox'][3]-bounds[1]]} for b in boxes]
        if crop.size:vehicle['focus_annotated_image_url']=annotate(crop,local(detections),local(heads),local(plates))
    unique_sources={s['url']:s for v in scene['potential_violations'] for s in v['sources']}
    scene['sources']=list(unique_sources.values())
    scene['fine_records']=[{'type':v['type'],'vehicle_id':v['vehicle_id'],'fine_amount':v['fine_amount'],
                            'fine_status':v['fine_status'],'rule':v['rule'],'effective_date':v['effective_date'],
                            'retrieval_status':'Structured official schedule','sources':v['sources']} for v in scene['potential_violations']]
    scene['jurisdiction']=jurisdiction
    scene['jurisdiction_basis']='User-selected application context; not inferred from the image'
    scene['rag_status']='Fine amounts use the independently verified structured registry; optional RAG is not required.'
    scene['ai_explanation']=(f"Local models detected {len(scene['vehicles'])} vehicle candidates. "
        f"The evidence rules support {scene['summary']['supported_findings']} potential findings. "
        'Helmet rules apply only to supported motorcycle/person relationships. Missing detections do not prove missing equipment. '
        'Unsupported conditions are marked Cannot determine from this image. All findings and plate readings need human review.')
    scene['explanation_status']='Deterministic explanation from actual model observations'
    scene['explanation']=scene['ai_explanation']
    scene['timings']['rules_and_fines_ms']=round((time.perf_counter()-started)*1000,1)
    return scene


async def analyze(path,repository,rag,settings,jurisdiction='Punjab'):
    result=await asyncio.to_thread(visual_analysis,path)
    return await asyncio.to_thread(finish_analysis,result,settings,jurisdiction)
